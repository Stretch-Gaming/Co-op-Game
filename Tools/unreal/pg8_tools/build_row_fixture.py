"""Compile an unsaved private fixture; no gameplay package or settings writes."""
import unreal as ue
import toolset_registry
from editor_toolset.toolsets.blueprint import BlueprintTools as BP
assert not ue.EditorLevelLibrary.get_pie_worlds(True)
bp=BP.create('/Game/Player/Test/ToolsAcceptance','BP_PG8_RowFixture_r48gb6azg9',ue.Actor.static_class())
graph=BP.add_function_graph(bp,'SetFixtureState')
game_state=ue.load_asset('/Game/Core/BP_CoopGameState').generated_class()
BP.add_object_function_param(graph,'GameState',game_state,True)
BP.add_struct_function_param(graph,'State',ue.load_asset('/Game/Core/S_RoundState'),True)
entry=next(n for n in BP.find_nodes(graph) if n.get_class().get_name()=='K2Node_FunctionEntry')
setter=BP.create_node(graph,'Class|BPCoopGameState|SetRoundState',ue.IntPoint(300,0),declaring_class=game_state)
assert setter
assert entry.find_then_pin().try_create_connection(setter.find_execute_pin())
assert entry.find_output_pin('GameState').try_create_connection(setter.find_input_pin('self'))
assert entry.find_output_pin('State').try_create_connection(setter.find_input_pin('RoundState'))
with toolset_registry.tool_raising_exceptions():
    BP.compile_blueprint(bp,warnings_as_errors=True)
assert bp.get_editor_property('status')==ue.BlueprintStatus.BS_UP_TO_DATE
RESULT={'fixture':bp.get_path_name(),'saved':False,'source':'original test Blueprint generated by this script; no third-party content'}
